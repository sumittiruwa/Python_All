# is_() methods return true or false 

txt = "Krishna Chaudhary"


print(txt.isalpha())		# all char are alphabet
print(txt.isdigit())		# all char are digit
print(txt.isalnum())		# all char are alphabet or digit
print(txt.islower())		# all char are in lower case
print(txt.isupper())		# all char are in upper case
print(txt.isspace())		# all char are space
print(txt.istitle())		# all char are in title case
print(txt.isprintable())	# all char are printable
print(txt.isidentifier())	# all char are valid identifier\
print(txt.startswith("krihsna"))	# string start with "Krishna"
print(txt.endswith("chaudhary"))	# string end with "Chaudhary
