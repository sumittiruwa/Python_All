# ceratibg sequences of numbers in numpy


import numpy as np

# arange(start, stop, step) function is used to create an array of evenly spaced values within a specified range
# start: The starting value of the sequence (inclusive).
# stop: The end value of the sequence (exclusive).
# step: The spacing between values.
arange_array = np.arange(0, 10, 2)
print(arange_array)